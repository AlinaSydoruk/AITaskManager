оценить по времени. Для этого тебе необходимо провести глубокий анализ предметной области.
 Оценивается задача в минутах. Если оценка уже задана, то ее следует проверить и задать оценку заново.
 Ответ должен быть строго в JSON-формате:
{ "estimate": число }

