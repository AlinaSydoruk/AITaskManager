    public function planTasks(array $tasks): array
    {
        $messages = [
        ['role' => 'system', 'content' => 'Ты — ассистент по тайм-менеджменту. тебе приходит задача которую необходимо будет оценить по времени. Оценивается задача в минутах'],
        ['role' => 'user', 'content' => 'Вот задача которую необходимо оценить по времени: ' . json_encode($tasks)],
    ];
        return $this->submit($messages);
    }




}